impl Lang {
    pub const ID: &'static Lang = id::ID;
    pub const EN: &'static Lang = en::EN;

    pub fn for_code(code: &str) -> &'static Lang {
        if code == crate::config::LANG_EN {
            Lang::EN
        } else {
            Lang::ID
        }
    }
}

use std::sync::Mutex;

/// Current UI language. Worker threads (console logs, install progress,
/// error messages) read this so the console never mixes Indonesian/English.
static CURRENT: Mutex<Option<&'static Lang>> = Mutex::new(None);

pub fn set_current(lang: &'static Lang) {
    if let Ok(mut c) = CURRENT.lock() {
        *c = Some(lang);
    }
}

pub fn current() -> &'static Lang {
    let guard = CURRENT.lock().unwrap();
    match *guard {
        Some(l) => l,
        None => &Lang::ID,
    }
}
